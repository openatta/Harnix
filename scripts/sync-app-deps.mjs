#!/usr/bin/env node
// Write Harnix's dependency table into an application's Cargo.toml.
//
//   node harnix/scripts/sync-app-deps.mjs [app-root]          rewrite the block
//   node harnix/scripts/sync-app-deps.mjs [app-root] --check  fail if it drifted
//
// An application's workspace takes `harnix/crates/*` in as members, so
// Harnix's crates resolve `xxx = { workspace = true }` against the
// *application's* `[workspace.dependencies]` (design §11.2). Harnix's own
// table is the one source of truth; this copies it into a marked block in
// the application's root Cargo.toml with every path rebased on the
// application's root — `crates/x` becomes `harnix/crates/x`, and `agix/…`
// stays `agix/…` because there `agix/` sits beside `harnix/`. Generated and
// checked, never hand-copied.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const BEGIN = "# BEGIN harnix — generated by harnix/scripts/sync-app-deps.mjs; do not edit";
export const END = "# END harnix";

const harnixRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The `[workspace.dependencies]` lines of Harnix's own Cargo.toml, rebased. */
export function block(harnix = harnixRoot) {
  const text = readFileSync(join(harnix, "Cargo.toml"), "utf8");
  const lines = text.split("\n");
  const start = lines.findIndex((l) => l.trim() === "[workspace.dependencies]");
  if (start < 0) throw new Error(`${harnix}/Cargo.toml has no [workspace.dependencies]`);
  const out = [];
  for (const line of lines.slice(start + 1)) {
    if (/^\s*\[/.test(line)) break;
    if (/^\s*#/.test(line) || !line.trim()) continue;
    out.push(
      line.replace(/path\s*=\s*"([^"]+)"/, (_, path) =>
        `path = "${path.startsWith("agix/") ? path : `harnix/${path}`}"`),
    );
  }
  return [BEGIN, ...out, END].join("\n");
}

/** The application's Cargo.toml with the block replaced (or added). */
export function rewrite(appToml, generated) {
  const at = appToml.indexOf(BEGIN);
  if (at >= 0) {
    const end = appToml.indexOf(END, at);
    if (end < 0) throw new Error(`the harnix block has no "${END}" line`);
    return appToml.slice(0, at) + generated + appToml.slice(end + END.length);
  }
  const header = appToml.indexOf("[workspace.dependencies]");
  if (header < 0) return `${appToml.trimEnd()}\n\n[workspace.dependencies]\n${generated}\n`;
  const after = appToml.indexOf("\n", header) + 1;
  return appToml.slice(0, after) + generated + "\n" + appToml.slice(after);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const appRoot = resolve(args.find((a) => !a.startsWith("--")) ?? join(harnixRoot, ".."));
  const path = join(appRoot, "Cargo.toml");
  const current = readFileSync(path, "utf8");
  const wanted = rewrite(current, block());
  if (check) {
    if (current !== wanted) {
      console.error(`${path}: the harnix block differs from harnix/Cargo.toml — run harnix/scripts/sync-app-deps.mjs`);
      process.exit(1);
    }
    console.log("sync-app-deps: in step");
  } else {
    writeFileSync(path, wanted);
    console.log(`sync-app-deps: wrote the harnix block into ${path}`);
  }
}
