fn ui_packages() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../ui/packages")
}

#[test]
fn export_the_protocol_types() {
    let cfg = Config::new().with_large_int("number");
    let files = [contract(&cfg), readers(&cfg), packages(&cfg), flow(&cfg), settings(&cfg)];
    let root = ui_packages();
    // `HARNIX_TS_CHECK`: compare instead of writing, and fail on a difference.
    let check = std::env::var_os("HARNIX_TS_CHECK").is_some_and(|v| !v.is_empty() && v != "0");
    let mut stale = Vec::new();
    for file in &files {
        let target = root.join(file.path);
        if check {
            if std::fs::read_to_string(&target).ok().as_deref() != Some(file.text.as_str()) {
                stale.push(file.path);
            }
        } else {
            std::fs::create_dir_all(target.parent().expect("a directory")).expect("create the output directory");
            std::fs::write(&target, &file.text).unwrap_or_else(|e| panic!("write {}: {e}", target.display()));
        }
    }
    assert!(
        stale.is_empty(),
        "generated protocol types are stale: {}\nregenerate: cargo test -p harnix --features ts --test ts_export",
        stale.join(", ")
    );
}
