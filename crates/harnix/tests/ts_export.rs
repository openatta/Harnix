//! The interface's protocol declarations, generated from the Rust types that serialize onto the
//! wire.
//!
//!     cargo test -p harnix --features ts --test ts_export                     # write them
//!     HARNIX_TS_CHECK=1 cargo test -p harnix --features ts --test ts_export   # fail if stale
//!
//! The output is committed. `scripts/check.sh` runs the second form, so a type changed on one side
//! and not the other is a red check rather than a refused handshake or a field read under a name
//! the server never sends (concept §5.2). Adding a field is: add it to the Rust struct, run the
//! first form, commit both.
//!
//! One file per source area rather than ts-rs's file per type: each is one diff to read, and each
//! is self-contained but for the engine's shapes, which are declared by hand (`../engine.ts`) and
//! imported — they are Agix's, outside this protocol's promise (`harnix-ext.md` §16), and a Rust
//! mirror of them would be a third copy with no check behind it either.
//!
//! Where a file goes: a type several UI packages read, or the shell, is `@harnix/core`'s; one a
//! single first-party package reads could be generated into that package instead (the first-party
//! packages do not import each other, `tests/ui-layering.mjs`).
#![cfg(feature = "ts")]

use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

/// One generated file: where it goes under `ui/packages`, and its whole text.
struct Generated {
    path: &'static str,
    text: String,
}

fn declaration<T: TS>(cfg: &Config) -> String {
    let docs = T::docs().map(|d| format!("{}\n", d.trim_end())).unwrap_or_default();
    format!("{docs}export {}\n", T::decl(cfg))
}

fn constant(docs: &str, name: &str, value: impl std::fmt::Display) -> String {
    format!("/** {docs} */\nexport const {name} = {value};\n")
}

macro_rules! declarations {
    ($cfg:expr; $($t:ty),+ $(,)?) => {
        vec![$(declaration::<$t>($cfg)),+]
    };
}

fn header(imports: &str) -> String {
    let mut out = String::from(
        "// Generated by crates/harnix/tests/ts_export.rs — do not edit.\n\
         // Regenerate: cargo test -p harnix --features ts --test ts_export\n\n",
    );
    if !imports.is_empty() {
        out += imports;
        out += "\n";
    }
    out
}

fn joined(header: String, parts: impl IntoIterator<Item = String>) -> String {
    let mut out = header;
    for part in parts {
        out += &part;
        out += "\n";
    }
    out.trim_end().to_string() + "\n"
}

/// `harnix-contract`: the versions, the error codes, the handshake, and the kernel's wire shapes.
fn contract(cfg: &Config) -> Generated {
    use harnix::codes;
    use harnix_contract::wire::*;
    use harnix_contract::{Channel, Handshake, Limits, RpcError, Subject, Topology};

    let mut parts = vec![
        constant(
            "Bumped when a method, an event shape or an error code changes in a way a client can observe.",
            "PROTOCOL_VERSION",
            harnix_contract::PROTOCOL_VERSION,
        ),
        constant(
            "The contribution point API — separate, because a UI bundle can be current on one and stale on the other.",
            "CONTRIB_API_VERSION",
            harnix_contract::CONTRIB_API_VERSION,
        ),
        constant("The largest single RPC frame a client may send.", "MAX_FRAME_BYTES", harnix_contract::MAX_FRAME_BYTES),
        constant("The largest file the bulk semantic accepts.", "MAX_UPLOAD_BYTES", harnix_contract::MAX_UPLOAD_BYTES),
        String::new(),
    ];
    for (docs, name, value) in [
        ("JSON-RPC: not JSON.", "PARSE_ERROR", codes::PARSE_ERROR),
        ("JSON-RPC: not a request.", "INVALID_REQUEST", codes::INVALID_REQUEST),
        ("JSON-RPC: no such method.", "METHOD_NOT_FOUND", codes::METHOD_NOT_FOUND),
        ("JSON-RPC: the params are wrong.", "INVALID_PARAMS", codes::INVALID_PARAMS),
        ("JSON-RPC: the server failed.", "INTERNAL_ERROR", codes::INTERNAL_ERROR),
        (
            "Harnix: the method exists and this subject may not call it. Outside JSON-RPC's reserved band, where Agix's codes live.",
            "REFUSED",
            codes::REFUSED,
        ),
        (
            "Harnix: the handshake did not agree — version, contribution API, or topology.",
            "HANDSHAKE_REFUSED",
            codes::HANDSHAKE_REFUSED,
        ),
        ("Harnix: the call named an instance this process does not have.", "INSTANCE_NOT_FOUND", codes::INSTANCE_NOT_FOUND),
        (
            "Harnix: the session does not belong to the space or instance the caller claimed. Guards against a client's bug, not a security boundary.",
            "SPACE_MISMATCH",
            codes::SPACE_MISMATCH,
        ),
        (
            "Harnix: the instance exists and cannot be reached right now; its status in `harnix.instances` says why.",
            "INSTANCE_UNAVAILABLE",
            codes::INSTANCE_UNAVAILABLE,
        ),
        (
            "Harnix: this connection already has `limits.max_in_flight` requests unanswered; send it again once one answers.",
            "BUSY",
            codes::BUSY,
        ),
        (
            "Harnix: the method exists and the thing it was asked about does not (no recording, no such run). Not `METHOD_NOT_FOUND`, which is about the method.",
            "NOT_FOUND",
            codes::NOT_FOUND,
        ),
        (
            "Harnix: what the call acts on changed under it (a lease that is not the caller's, a revision that moved on); read it again before trying again.",
            "CONFLICT",
            codes::CONFLICT,
        ),
        (
            "Harnix: the call was cancelled before it answered, by its caller or because what it was made for was.",
            "CANCELLED",
            codes::CANCELLED,
        ),
        (
            "Harnix: the call's deadline passed before it answered or before it started; an extension package's backend that outruns its `timeout_ms` is this too.",
            "DEADLINE_EXCEEDED",
            codes::DEADLINE_EXCEEDED,
        ),
        (
            "Harnix: the extension is there and cannot answer now; `data.failure` is `starting`, `stopped`, `faulted` or `reentrant`. An instance out of reach is `INSTANCE_UNAVAILABLE`.",
            "EXTENSION_UNAVAILABLE",
            codes::EXTENSION_UNAVAILABLE,
        ),
    ] {
        parts.push(constant(docs, name, value));
    }
    parts.push(String::new());
    parts.extend(declarations![cfg;
        // The handshake.
        Topology, Handshake, Limits, Subject, Channel, RpcError,
        // `harnix.hello` and `harnix.ui`.
        Hello, HelloEngine, EngineProviders, ProviderModels, EngineTrust, HelloInstance, HelloDefaults, HelloShell, Brand,
        NarrowDetails, ExtensionEntry, UiView,
        // Instances.
        InstanceCarrier, LinkStatus, InstanceRow, InstancesList,
        // Sessions: the hub's lists, topics and answers.
        Waiting, StartedBy, SessionActivity, HubSessionRow, SessionsList, SessionStatusRow, SessionsStatus, SpaceRow,
        SpacesList, QueueItem, ReplayFrame, AttachResult,
        // The hub's frames.
        EventFrame, ToolCallOutcome, TurnOutcome, TurnSettled, QueueFrame, SessionResync, TopicFrame, TopicEnded,
    ]);
    Generated {
        path: "core/src/protocol/generated/contract.ts",
        text: joined(
            header("import type { EngineEvent, Goal, PromptEvent, Scene, SessionInfo, SessionRow, Usage } from \"../engine.ts\";\n"),
            parts,
        ),
    }
}

/// `harnix-engine-api`'s readers: what `observability.*` answers.
fn readers(cfg: &Config) -> Generated {
    use harnix::engine::readers::*;
    Generated {
        path: "core/src/protocol/generated/readers.ts",
        text: joined(
            header("import type { Usage } from \"../engine.ts\";\n"),
            declarations![cfg;
                RecordingRun, Trace, CallSummary, CallInput, BlockSize, CallOutput, ToolUseSummary, Timing,
                CallDetail, CallDetailInput, CallDetailOutput, ToolResultView, SystemBlock,
                Turns, TurnSummary, Envelopes, Envelope, SessionUsage, AgentUsage, SearchHit, SearchResult,
            ],
        ),
    }
}

fn ui_packages() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../ui/packages")
}

#[test]
fn export_the_protocol_types() {
    let cfg = Config::new().with_large_int("number");
    let files = [contract(&cfg), readers(&cfg)];
    let root = ui_packages();
    // `HARNIX_TS_CHECK`: compare instead of writing, and fail on a difference.
    let check = std::env::var_os("HARNIX_TS_CHECK").is_some_and(|v| !v.is_empty() && v != "0");
    let mut stale = Vec::new();
    for file in &files {
        let target = root.join(file.path);
        if check {
            if std::fs::read_to_string(&target).ok().as_deref() != Some(file.text.as_str()) {
                stale.push(file.path);
            }
        } else {
            std::fs::create_dir_all(target.parent().expect("a directory")).expect("create the output directory");
            std::fs::write(&target, &file.text).unwrap_or_else(|e| panic!("write {}: {e}", target.display()));
        }
    }
    assert!(
        stale.is_empty(),
        "generated protocol types are stale: {}\nregenerate: cargo test -p harnix --features ts --test ts_export",
        stale.join(", ")
    );
}
