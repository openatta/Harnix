//! The interface's protocol declarations, generated from the Rust types that serialize onto the
//! wire.
//!
//!     cargo test -p harnix --features ts --test ts_export                     # write them
//!     HARNIX_TS_CHECK=1 cargo test -p harnix --features ts --test ts_export   # fail if stale
//!
//! The output is committed. `scripts/check.sh` runs the second form, so a type changed on one side
//! and not the other is a red check rather than a refused handshake or a field read under a name
//! the server never sends (concept §5.2). Adding a field is: add it to the Rust struct, run the
//! first form, commit both.
//!
//! One file per source area rather than ts-rs's file per type: each is one diff to read, and each
//! is self-contained but for the engine's shapes, which are declared by hand (`../engine.ts`) and
//! imported — they are Agix's, outside this protocol's promise (`harnix-ext.md` §16), and a Rust
//! mirror of them would be a third copy with no check behind it either.
//!
//! Where a file goes: a type several UI packages read, or the shell, is `@harnix/core`'s; one a
//! single first-party package reads could be generated into that package instead (the first-party
//! packages do not import each other, `tests/ui-layering.mjs`).
#![cfg(feature = "ts")]

use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

/// One generated file: where it goes under `ui/packages`, and its whole text.
struct Generated {
    path: &'static str,
    text: String,
}

fn declaration<T: TS>(cfg: &Config) -> String {
    let docs = T::docs().map(|d| format!("{}\n", d.trim_end())).unwrap_or_default();
    format!("{docs}export {}\n", T::decl(cfg))
}

fn constant(docs: &str, name: &str, value: impl std::fmt::Display) -> String {
    format!("/** {docs} */\nexport const {name} = {value};\n")
}

macro_rules! declarations {
    ($cfg:expr; $($t:ty),+ $(,)?) => {
        vec![$(declaration::<$t>($cfg)),+]
    };
}

fn header(imports: &str) -> String {
    let mut out = String::from(
        "// Generated by crates/harnix/tests/ts_export.rs — do not edit.\n\
         // Regenerate: cargo test -p harnix --features ts --test ts_export\n\n",
    );
    if !imports.is_empty() {
        out += imports;
        out += "\n";
    }
    out
}

fn joined(header: String, parts: impl IntoIterator<Item = String>) -> String {
    let mut out = header;
    for part in parts {
        out += &part;
        out += "\n";
    }
    out.trim_end().to_string() + "\n"
}

/// `harnix-contract`: the versions, the error codes, the handshake, and the kernel's wire shapes.
