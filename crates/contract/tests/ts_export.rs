//! `@harnix/core/protocol`'s declarations, generated from the types here.
//!
//! Run with `cargo test -p harnix-contract --features ts`. The output is
//! committed; `scripts/check.sh` regenerates it into a scratch directory
//! (`HARNIX_TS_OUT`) and fails on any difference, so a type changed on one
//! side and not the other is a red check rather than a refused handshake
//! (design §4.2).
//!
//! One file rather than ts-rs's file per type: the set is small, and one file
//! is one diff to read.
#![cfg(feature = "ts")]

use std::path::PathBuf;

use harnix_contract::{codes, Channel, Handshake, Limits, RpcError, Subject, Topology};
use ts_rs::{Config, TS};

fn declaration<T: TS>(cfg: &Config) -> String {
    let docs = T::docs().map(|d| format!("{}\n", d.trim_end())).unwrap_or_default();
    format!("{docs}export {}\n", T::decl(cfg))
}

fn constant(docs: &str, name: &str, value: impl std::fmt::Display) -> String {
    format!("/** {docs} */\nexport const {name} = {value};\n")
}

#[test]
fn export_the_protocol_types() {
    let cfg = Config::new().with_large_int("number");
    let mut out = String::from(
        "// Generated by crates/contract/tests/ts_export.rs — do not edit.\n\
         // Regenerate: cargo test -p harnix-contract --features ts\n\n",
    );
    out += &constant(
        "Bumped when a method, an event shape or an error code changes in a way a client can observe.",
        "PROTOCOL_VERSION",
        harnix_contract::PROTOCOL_VERSION,
    );
    out += &constant(
        "The contribution point API — separate, because a UI bundle can be current on one and stale on the other.",
        "CONTRIB_API_VERSION",
        harnix_contract::CONTRIB_API_VERSION,
    );
    out += &constant(
        "The largest single RPC frame a client may send.",
        "MAX_FRAME_BYTES",
        harnix_contract::MAX_FRAME_BYTES,
    );
    out += &constant(
        "The largest file the bulk semantic accepts.",
        "MAX_UPLOAD_BYTES",
        harnix_contract::MAX_UPLOAD_BYTES,
    );
    out += "\n";
    for (docs, name, value) in [
        ("JSON-RPC: not JSON.", "PARSE_ERROR", codes::PARSE_ERROR),
        ("JSON-RPC: not a request.", "INVALID_REQUEST", codes::INVALID_REQUEST),
        ("JSON-RPC: no such method.", "METHOD_NOT_FOUND", codes::METHOD_NOT_FOUND),
        ("JSON-RPC: the params are wrong.", "INVALID_PARAMS", codes::INVALID_PARAMS),
        ("JSON-RPC: the server failed.", "INTERNAL_ERROR", codes::INTERNAL_ERROR),
        (
            "Harnix: the method exists and this subject may not call it. Outside JSON-RPC's reserved band, where Agix's codes live.",
            "REFUSED",
            codes::REFUSED,
        ),
        (
            "Harnix: the handshake did not agree — version, contribution API, or topology.",
            "HANDSHAKE_REFUSED",
            codes::HANDSHAKE_REFUSED,
        ),
        (
            "Harnix: the call named an instance this process does not have.",
            "INSTANCE_NOT_FOUND",
            codes::INSTANCE_NOT_FOUND,
        ),
        (
            "Harnix: the session does not belong to the space or instance the caller claimed. Guards against a client's bug, not a security boundary.",
            "SPACE_MISMATCH",
            codes::SPACE_MISMATCH,
        ),
    ] {
        out += &constant(docs, name, value);
    }
    out += "\n";
    for decl in [
        declaration::<Topology>(&cfg),
        declaration::<Handshake>(&cfg),
        declaration::<Limits>(&cfg),
        declaration::<Subject>(&cfg),
        declaration::<Channel>(&cfg),
        declaration::<RpcError>(&cfg),
    ] {
        out += &decl;
        out += "\n";
    }

    let dir = std::env::var_os("HARNIX_TS_OUT")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(env!("CARGO_MANIFEST_DIR"))
                .join("../../ui/packages/core/src/protocol/generated")
        });
    std::fs::create_dir_all(&dir).expect("create the output directory");
    std::fs::write(dir.join("contract.ts"), out.trim_end().to_string() + "\n")
        .expect("write contract.ts");
}
